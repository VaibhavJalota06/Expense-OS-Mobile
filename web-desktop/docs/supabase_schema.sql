-- 8. CONVENIENCE REPORTING & EXPORT VIEWS

CREATE OR REPLACE VIEW public.vw_user_expenses_export AS
SELECT 
    ud.user_id,
    ud.currency,
    exp->>'id' AS transaction_id,
    exp->>'date' AS transaction_date,
    exp->>'category' AS category,
    exp->>'description' AS description,
    exp->>'payment' AS payment_method,
    (exp->>'amount')::NUMERIC AS amount
FROM public.user_data ud,
LATERAL jsonb_array_elements(ud.expenses) AS exp;

CREATE OR REPLACE VIEW public.vw_user_subscriptions_export AS
SELECT 
    ud.user_id,
    ud.currency,
    sub->>'id' AS subscription_id,
    sub->>'name' AS bill_name,
    sub->>'category' AS category,
    (sub->>'amount')::NUMERIC AS monthly_cost,
    sub->>'date' AS billing_date
FROM public.user_data ud,
LATERAL jsonb_array_elements(ud.subscriptions) AS sub;

CREATE OR REPLACE VIEW public.vw_admin_all_user_expenses AS
SELECT 
    ud.user_id AS user_account_id,
    exp->>'date' AS transaction_date,
    exp->>'category' AS category,
    exp->>'description' AS description,
    exp->>'payment' AS payment_method,
    (exp->>'amount')::NUMERIC AS amount_spent,
    ud.currency AS base_currency,
    ud.updated_at AS last_synced_at
FROM public.user_data ud
LEFT JOIN LATERAL jsonb_array_elements(ud.expenses) AS exp ON true
ORDER BY ud.updated_at DESC, exp->>'date' DESC;

CREATE OR REPLACE VIEW public.vw_admin_user_summaries AS
SELECT 
    ud.user_id AS user_account_id,
    ud.currency AS base_currency,
    ud.budget AS monthly_budget_cap,
    jsonb_array_length(ud.expenses) AS total_expenses_count,
    jsonb_array_length(ud.subscriptions) AS total_subscriptions_count,
    jsonb_array_length(ud.incomes) AS total_incomes_count,
    ud.updated_at AS last_active_time
FROM public.user_data ud
ORDER BY ud.updated_at DESC;
