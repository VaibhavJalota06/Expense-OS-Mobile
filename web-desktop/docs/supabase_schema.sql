-- 1. CREATE ALL 9 CORE TABLES IF NOT EXISTS

-- Table 1: Profiles
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT,
  display_name TEXT,
  full_name TEXT,
  gender TEXT DEFAULT 'male',
  avatar_url TEXT,
  phone TEXT DEFAULT '',
  job TEXT DEFAULT '',
  country TEXT DEFAULT 'United States',
  bio TEXT DEFAULT '',
  currency TEXT DEFAULT 'INR',
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now(),
  CONSTRAINT profiles_user_id_unique UNIQUE (user_id)
);

-- Table 2: Expenses
CREATE TABLE IF NOT EXISTS public.expenses (
  id TEXT PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  amount NUMERIC NOT NULL DEFAULT 0,
  category TEXT DEFAULT 'Miscellaneous',
  description TEXT DEFAULT '',
  payment TEXT DEFAULT 'Cash',
  date TEXT DEFAULT '',
  tags JSONB DEFAULT '[]'::jsonb,
  receipt_url TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- Table 3: Budgets
CREATE TABLE IF NOT EXISTS public.budgets (
  id TEXT PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  category TEXT DEFAULT 'ALL',
  amount NUMERIC DEFAULT 0,
  month TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- Table 4: Categories
CREATE TABLE IF NOT EXISTS public.categories (
  id TEXT PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  color TEXT DEFAULT '#34D399',
  icon TEXT DEFAULT 'fa-tag',
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- Table 5: Subscriptions & Recurring Bills
CREATE TABLE IF NOT EXISTS public.subscriptions (
  id TEXT PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  amount NUMERIC DEFAULT 0,
  category TEXT DEFAULT 'Services & Subscriptions',
  date TEXT DEFAULT '',
  billing_cycle TEXT DEFAULT 'Monthly',
  next_due TEXT DEFAULT '',
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- Table 6: Split Bills (Group Expenses)
CREATE TABLE IF NOT EXISTS public.split_bills (
  id TEXT PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  total_amount NUMERIC DEFAULT 0,
  date TEXT DEFAULT '',
  category TEXT DEFAULT 'Food & Dining',
  payer TEXT DEFAULT 'You',
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- Table 7: Split Bill Members
CREATE TABLE IF NOT EXISTS public.split_bill_members (
  id TEXT PRIMARY KEY,
  bill_id TEXT REFERENCES public.split_bills(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  share_amount NUMERIC DEFAULT 0,
  is_paid BOOLEAN DEFAULT false,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- Table 8: Export Templates
CREATE TABLE IF NOT EXISTS public.export_templates (
  template_id TEXT PRIMARY KEY DEFAULT 'default_executive_template',
